-- MediChannel database schema
-- Database: PostgreSQL 14+
-- Encoding: UTF8
--
-- Run with:
--   psql -U <username> -d <database_name> -f schema.sql
--
-- Notes:
-- 1. Encrypted values are stored as TEXT/VARCHAR ciphertext. Do not use DATE
--    for encrypted dates of birth.
-- 2. email_hmac and nic_hmac are deterministic keyed hashes used for lookup
--    and uniqueness; never store plaintext identifiers for this purpose.
-- 3. This schema models one payment and one feedback record per appointment.
--    Remove the UNIQUE constraint on payments.appointment_id if partial or
--    multiple payments are required.

BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_ciphertext TEXT NOT NULL,
    email_hmac VARCHAR(128) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    locked BOOLEAN NOT NULL DEFAULT FALSE,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_role_check
        CHECK (role IN ('admin', 'patient', 'doctor', 'staff')),
    CONSTRAINT users_failed_login_check
        CHECK (failed_login_attempts >= 0)
);

CREATE TABLE patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    full_name_ciphertext TEXT NOT NULL,
    nic_ciphertext TEXT,
    nic_hmac VARCHAR(128) UNIQUE,
    phone_ciphertext TEXT,
    address_ciphertext TEXT,
    date_of_birth_ciphertext TEXT,
    gender_ciphertext TEXT,
    CONSTRAINT patients_user_fk
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE specialisations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE doctors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    specialisation_id BIGINT NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    slmc_number VARCHAR(80) NOT NULL UNIQUE,
    qualifications TEXT,
    consultation_fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    bio TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT doctors_user_fk
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT doctors_specialisation_fk
        FOREIGN KEY (specialisation_id) REFERENCES specialisations(id)
        ON DELETE RESTRICT,
    CONSTRAINT doctors_fee_check CHECK (consultation_fee >= 0)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(50) NOT NULL UNIQUE,
    location VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    session_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    session_type VARCHAR(50) NOT NULL,
    max_patients INTEGER NOT NULL,
    minutes_per_patient INTEGER NOT NULL,
    fee NUMERIC(12, 2) NOT NULL DEFAULT 0,
    delay_minutes INTEGER NOT NULL DEFAULT 0,
    next_appointment_number INTEGER NOT NULL DEFAULT 1,
    current_appointment_number INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'scheduled',
    CONSTRAINT sessions_doctor_fk
        FOREIGN KEY (doctor_id) REFERENCES doctors(id) ON DELETE RESTRICT,
    CONSTRAINT sessions_room_fk
        FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE RESTRICT,
    CONSTRAINT sessions_time_check CHECK (end_time > start_time),
    CONSTRAINT sessions_capacity_check CHECK (max_patients > 0),
    CONSTRAINT sessions_slot_duration_check CHECK (minutes_per_patient > 0),
    CONSTRAINT sessions_fee_check CHECK (fee >= 0),
    CONSTRAINT sessions_delay_check CHECK (delay_minutes >= 0),
    CONSTRAINT sessions_appointment_counter_check
        CHECK (
            next_appointment_number > 0
            AND current_appointment_number >= 0
            AND current_appointment_number <= max_patients
        ),
    CONSTRAINT sessions_status_check
        CHECK (status IN ('scheduled', 'in_progress', 'completed', 'cancelled'))
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    appointment_number INTEGER NOT NULL,
    booking_reference VARCHAR(100) NOT NULL UNIQUE,
    reason_ciphertext TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'booked',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    booked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT appointments_patient_fk
        FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE RESTRICT,
    CONSTRAINT appointments_session_fk
        FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE RESTRICT,
    CONSTRAINT appointments_session_number_unique
        UNIQUE (session_id, appointment_number),
    CONSTRAINT appointments_number_check CHECK (appointment_number > 0),
    CONSTRAINT appointments_status_check
        CHECK (status IN ('booked', 'confirmed', 'cancelled', 'completed', 'no_show')),
    CONSTRAINT appointments_payment_status_check
        CHECK (payment_status IN ('pending', 'paid', 'partially_paid', 'refunded', 'failed'))
);

CREATE TABLE consultations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE,
    diagnosis_ciphertext TEXT,
    advice_ciphertext TEXT,
    prescription_ciphertext TEXT,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    CONSTRAINT consultations_appointment_fk
        FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT,
    CONSTRAINT consultations_time_check
        CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    sender_user_id BIGINT NOT NULL,
    message_ciphertext TEXT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_status BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chat_messages_appointment_fk
        FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
    CONSTRAINT chat_messages_sender_fk
        FOREIGN KEY (sender_user_id) REFERENCES users(id) ON DELETE RESTRICT
);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE,
    amount NUMERIC(12, 2) NOT NULL,
    payment_method VARCHAR(40) NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    paid_at TIMESTAMPTZ,
    recorded_by BIGINT,
    CONSTRAINT payments_appointment_fk
        FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT,
    CONSTRAINT payments_recorded_by_fk
        FOREIGN KEY (recorded_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT payments_amount_check CHECK (amount >= 0),
    CONSTRAINT payments_status_check
        CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded', 'cancelled'))
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    notification_type VARCHAR(80) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notifications_user_fk
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE,
    doctor_id BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    comment TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT feedback_appointment_fk
        FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
    CONSTRAINT feedback_doctor_fk
        FOREIGN KEY (doctor_id) REFERENCES doctors(id) ON DELETE RESTRICT,
    CONSTRAINT feedback_rating_check CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT feedback_status_check
        CHECK (status IN ('pending', 'approved', 'rejected', 'hidden'))
);

CREATE TABLE notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT notices_created_by_fk
        FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100),
    entity_id BIGINT,
    ip_address INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_logs_user_fk
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- Indexes for common lookups, joins, dashboards, and chronological queries.
CREATE INDEX idx_doctors_specialisation_active
    ON doctors (specialisation_id, active);

CREATE INDEX idx_sessions_doctor_date_status
    ON sessions (doctor_id, session_date, status);

CREATE INDEX idx_sessions_room_date
    ON sessions (room_id, session_date);

CREATE INDEX idx_appointments_patient_booked
    ON appointments (patient_id, booked_at DESC);

CREATE INDEX idx_appointments_session_status
    ON appointments (session_id, status);

CREATE INDEX idx_chat_messages_appointment_sent
    ON chat_messages (appointment_id, sent_at);

CREATE INDEX idx_notifications_user_unread
    ON notifications (user_id, is_read, created_at DESC);

CREATE INDEX idx_feedback_doctor_status
    ON feedback (doctor_id, status, created_at DESC);

CREATE INDEX idx_notices_published_date
    ON notices (published, published_at DESC);

CREATE INDEX idx_audit_logs_user_created
    ON audit_logs (user_id, created_at DESC);

CREATE INDEX idx_audit_logs_entity
    ON audit_logs (entity_type, entity_id);

COMMIT;
